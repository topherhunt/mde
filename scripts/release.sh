#!/bin/bash
# Publishes the current main commit as a GitHub release. Run with:
#   bash scripts/release.sh
#
# The version comes from package.json, so bump and commit it first. Refuses
# unless you're on main with a clean tree that matches origin/main and the
# version isn't already released. The Windows installer can't be built on a Mac,
# so the "Build and Release" workflow builds both installers into a draft
# release; you're asked to confirm once both are attached. It never commits or
# pushes: publishing the draft creates the tag on GitHub at that exact commit.
set -euo pipefail
cd "$(dirname "$0")/.."

die() { echo "!! $*" >&2; exit 1; }

[ $# -eq 0 ] || die "takes no arguments; the version comes from package.json"
VERSION="$(node -p "require('./package.json').version")"
echo "$VERSION" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$' || die "package.json version is '$VERSION'; it must look like 1.2.3"
TAG="v$VERSION"

echo "==> preflight"
command -v gh >/dev/null       || die "gh is not installed:  brew install gh"
gh auth status >/dev/null 2>&1 || die "gh is not logged in:  gh auth login"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
[ "$BRANCH" = "main" ] || die "on branch '$BRANCH'; releases are cut from main"
[ -z "$(git status --porcelain)" ] || die "uncommitted changes; commit or discard them first"
git fetch --quiet origin main
[ "$(git rev-parse HEAD)" = "$(git rev-parse origin/main)" ] \
  || die "main and origin/main differ; push (or pull) first"
[ -z "$(git ls-remote --tags origin "refs/tags/$TAG")" ] \
  || die "$TAG is already released; bump the version in package.json, commit, and push"
# A draft has no tag yet, so the check above can't see one left by an aborted run.
! gh release view "$TAG" >/dev/null 2>&1 \
  || die "a draft release for $TAG already exists; delete it first:  gh release delete $TAG"
COMMIT="$(git rev-parse HEAD)"

echo "==> testing"
npm test

echo "==> building in CI"
DISPATCH="$(gh workflow run release.yml --ref main -f release=true 2>&1)"
RUN_URL="$(echo "$DISPATCH" | grep -Eo 'https://[^ ]+/actions/runs/[0-9]+' | head -1 || true)"
[ -n "$RUN_URL" ] || die "gh didn't report the run it started:  $DISPATCH"
RUN_ID="${RUN_URL##*/}"
[ "$(gh run view "$RUN_ID" --json headSha -q .headSha)" = "$COMMIT" ] \
  || die "CI is building a different commit than ${COMMIT:0:10} (was main pushed meanwhile?): $RUN_URL"
echo "    $RUN_URL"
gh run watch "$RUN_ID" --exit-status --compact >/dev/null || die "CI build failed: $RUN_URL"

ASSETS="$(gh release view "$TAG" --json assets -q '.assets[] | "           \(.name) (\(.size / 1048576 | floor) MB)"')"
echo "$ASSETS" | grep -q '\.dmg ' || die "the draft has no .dmg; see $RUN_URL"
echo "$ASSETS" | grep -q '\.exe ' || die "the draft has no Windows .exe; see $RUN_URL"

cat <<SUMMARY

------------------------------------------------------------
Ready to publish $TAG
  commit   ${COMMIT:0:10} ($(git log -1 --format=%s))
  repo     $(gh repo view --json nameWithOwner -q .nameWithOwner)
  draft    $(gh release view "$TAG" --json url -q .url)
  assets
$ASSETS
  notes    generated by GitHub from commits since the last release
------------------------------------------------------------
Smoke-test the installers from the draft first if you like.
SUMMARY

read -r -p "Publish? [y/N] " reply
[ "$reply" = "y" ] || [ "$reply" = "Y" ] \
  || die "aborted; $TAG is an unpublished draft. Publish it on GitHub, or:  gh release delete $TAG"

gh release edit "$TAG" --draft=false
git fetch --quiet --tags origin

echo
echo "Published: $(gh release view "$TAG" --json url -q .url)"
